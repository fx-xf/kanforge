"""Triton kernels for CUDA and ROCm (and CPU under ``TRITON_INTERPRET=1``).

For every (plan, native order, feature count) a small module is generated
into the cache directory (Triton needs real source files) with:

  _phi(xv, i, grid_ptr, rk)  -> (BB, NP) features of a block of inputs
  kf_F, kf_G, kf_P           -> the three primitives of ``kanforge.kernels``

The basis code is unrolled at generation time; the contractions use
``tl.dot`` with IEEE float32 precision (no TF32) on (32 x 32 x NP) tiles.
"""

from __future__ import annotations

import hashlib
import importlib.util
import math
import os
from functools import lru_cache
from pathlib import Path

from .plan import KernelPlan

BB = 32  # batch rows per tile
BO = 32  # outputs per tile


def _f(v: float) -> str:
    return repr(float(v))


def _phi_source(plan: KernelPlan, m: int, nf: int) -> str:
    lines = []
    if plan.kind == "cheb":
        _, input_map = plan.consts
        lines.append("z = _tanh(xv)" if input_map == "tanh" else "z = xv")
        lines.append("f0 = xv * 0.0 + 1.0")
        if nf > 1:
            lines.append("f1 = z")
        for j in range(2, nf):
            lines.append(f"f{j} = 2.0 * z * f{j - 1} - f{j - 2}")
        names = [f"f{j}" for j in range(nf)]
    elif plan.kind == "fourier":
        freqs, period = plan.consts
        w0 = 2 * math.pi / period
        for j in range(freqs):
            lines.append(f"a{j} = {_f((j + 1) * w0)} * xv")
            lines.append(f"f{j} = tl.cos(a{j})")
            lines.append(f"f{freqs + j} = tl.sin(a{j})")
        names = [f"f{j}" for j in range(2 * freqs)]
    elif plan.kind == "bspline":
        g, k = plan.consts
        nk = g + 2 * k + 1
        lines.append(f"g0 = tl.load(grid_ptr + i * {g + 1})")
        lines.append(f"gl = tl.load(grid_ptr + i * {g + 1} + {g})")
        lines.append(f"h = (gl - g0) / {_f(g)}")
        for r in range(nk):
            if r < k:
                lines.append(f"t{r} = g0 - {_f(k - r)} * h")
            elif r <= k + g:
                lines.append(f"t{r} = tl.load(grid_ptr + i * {g + 1} + {r - k})")
            else:
                lines.append(f"t{r} = gl + {_f(r - k - g)} * h")
        if m > k:
            names = ["(xv * 0.0)"] * plan.size
        else:
            for j in range(nk - 1):
                lines.append(f"b0_{j} = tl.where((xv >= t{j}) & (xv < t{j + 1}), 1.0, 0.0)")
            level = 0
            for q in range(1, k - m + 1):
                for j in range(nk - 1 - q):
                    lines.append(
                        f"b{q}_{j} = (xv - t{j}) / (t{j + q} - t{j}) * b{q - 1}_{j}"
                        f" + (t{j + q + 1} - xv) / (t{j + q + 1} - t{j + 1}) * b{q - 1}_{j + 1}"
                    )
                level = q
            for q in range(k - m + 1, k + 1):
                for j in range(nk - 1 - q):
                    lines.append(
                        f"b{q}_{j} = {_f(q)} * (b{q - 1}_{j} / (t{j + q} - t{j})"
                        f" - b{q - 1}_{j + 1} / (t{j + q + 1} - t{j + 1}))"
                    )
                level = q
            names = [f"b{level}_{j}" for j in range(plan.size)]
    elif plan.kind == "bump":
        mode, count, u_scale, norm, _ = plan.consts
        poly = plan.bump_poly(m)
        lines.append(f"c0 = tl.load(grid_ptr + i * {count})")
        lines.append(f"cl = tl.load(grid_ptr + i * {count} + {count - 1})")
        lines.append(f"s = {_f(u_scale * (count - 1))} / (cl - c0)")
        lines.append("sm = " + (" * ".join(["s"] * m) if m else "1.0"))
        for j in range(count):
            lines.append(f"u{j} = (xv - tl.load(grid_ptr + i * {count} + {j})) * s")
            t = f"_tanh(u{j})" if mode == "tanh" else f"u{j}"
            lines.append(f"t{j} = {t}")
            horner = _f(poly[-1])
            for c in reversed(poly[:-1]):
                horner = f"({horner} * t{j} + {_f(c)})"
            env = f" * tl.exp(-0.5 * u{j} * u{j})" if mode == "gauss" else ""
            lines.append(f"f{j} = {_f(norm)} * {horner}{env} * sm")
        names = [f"f{j}" for j in range(count)]
    else:
        raise ValueError(plan.kind)
    lines.append("phi = xv[:, None] * 0.0 + rk[None, :] * 0.0")
    for j, name in enumerate(names):
        lines.append(f"phi = tl.where(rk[None, :] == {j}, ({name})[:, None], phi)")
    lines.append("return phi")
    return "\n".join("    " + line for line in lines)


TEMPLATE = '''# Generated by kanforge.kernels.triton_kernels — do not edit.
import triton
import triton.language as tl


@triton.jit
def _tanh(x):
    t = tl.exp(-2.0 * tl.abs(x))
    r = (1.0 - t) / (1.0 + t)
    return tl.where(x >= 0, r, -r)


@triton.jit
def _phi(xv, i, grid_ptr, rk):
{phi}


@triton.jit
def kf_F(x_ptr, w_ptr, c_ptr, grid_ptr, y_ptr, B,
         IN: tl.constexpr, OUT: tl.constexpr, NF: tl.constexpr, NP: tl.constexpr,
         BB: tl.constexpr, BO: tl.constexpr):
    pb = tl.program_id(0)
    po = tl.program_id(1)
    rb = pb * BB + tl.arange(0, BB)
    ro = po * BO + tl.arange(0, BO)
    rk = tl.arange(0, NP)
    mb = rb < B
    mo = ro < OUT
    mk = rk < NF
    acc = tl.zeros((BB, BO), dtype=tl.float32)
    for i in range(IN):
        xv = tl.load(x_ptr + rb * IN + i, mask=mb, other=0.0)
        wv = tl.load(w_ptr + rb * IN + i, mask=mb, other=0.0)
        phi = _phi(xv, i, grid_ptr, rk) * wv[:, None]
        cb = tl.load(c_ptr + (ro[None, :] * IN + i) * NF + rk[:, None], mask=mk[:, None] & mo[None, :], other=0.0)
        acc += tl.dot(phi, cb, input_precision="ieee")
    tl.store(y_ptr + rb[:, None] * OUT + ro[None, :], acc, mask=mb[:, None] & mo[None, :])


@triton.jit
def kf_G(x_ptr, w_ptr, g_ptr, grid_ptr, out_ptr, B,
         IN: tl.constexpr, OUT: tl.constexpr, NF: tl.constexpr, NP: tl.constexpr,
         BB: tl.constexpr, BO: tl.constexpr):
    i = tl.program_id(0)
    po = tl.program_id(1)
    ro = po * BO + tl.arange(0, BO)
    rk = tl.arange(0, NP)
    mo = ro < OUT
    mk = rk < NF
    acc = tl.zeros((BO, NP), dtype=tl.float32)
    for b0 in range(0, B, BB):
        rb = b0 + tl.arange(0, BB)
        mb = rb < B
        xv = tl.load(x_ptr + rb * IN + i, mask=mb, other=0.0)
        wv = tl.load(w_ptr + rb * IN + i, mask=mb, other=0.0)
        phi = _phi(xv, i, grid_ptr, rk) * wv[:, None]
        gb = tl.load(g_ptr + rb[:, None] * OUT + ro[None, :], mask=mb[:, None] & mo[None, :], other=0.0)
        acc += tl.dot(tl.trans(gb), phi, input_precision="ieee")
    tl.store(out_ptr + (ro[:, None] * IN + i) * NF + rk[None, :], acc, mask=mo[:, None] & mk[None, :])


@triton.jit
def kf_P(x_ptr, g_ptr, c_ptr, grid_ptr, p_ptr, B,
         IN: tl.constexpr, OUT: tl.constexpr, NF: tl.constexpr, NP: tl.constexpr,
         BB: tl.constexpr, BO: tl.constexpr):
    pb = tl.program_id(0)
    i = tl.program_id(1)
    rb = pb * BB + tl.arange(0, BB)
    rk = tl.arange(0, NP)
    mb = rb < B
    mk = rk < NF
    xv = tl.load(x_ptr + rb * IN + i, mask=mb, other=0.0)
    phi = _phi(xv, i, grid_ptr, rk)
    h = tl.zeros((BB, NP), dtype=tl.float32)
    for o0 in range(0, OUT, BO):
        ro = o0 + tl.arange(0, BO)
        mo = ro < OUT
        gb = tl.load(g_ptr + rb[:, None] * OUT + ro[None, :], mask=mb[:, None] & mo[None, :], other=0.0)
        cb = tl.load(c_ptr + (ro[:, None] * IN + i) * NF + rk[None, :], mask=mo[:, None] & mk[None, :], other=0.0)
        h += tl.dot(gb, cb, input_precision="ieee")
    tl.store(p_ptr + rb * IN + i, tl.sum(h * phi, axis=1), mask=mb)
'''


def module_source(plan: KernelPlan, m: int, nf: int) -> str:
    return TEMPLATE.format(phi=_phi_source(plan, m, nf))


def _cache_dir() -> Path:
    root = os.environ.get("KANFORGE_CACHE") or os.path.join(os.path.expanduser("~"), ".cache", "kanforge")
    path = Path(root) / "triton"
    path.mkdir(parents=True, exist_ok=True)
    return path


@lru_cache(maxsize=256)
def _module(plan: KernelPlan, m: int, nf: int):
    src = module_source(plan, m, nf)
    name = "kf_" + hashlib.sha1(src.encode()).hexdigest()[:16]
    path = _cache_dir() / f"{name}.py"
    if not path.exists():
        tmp = path.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text(src)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _np(nf: int) -> int:
    return max(16, 1 << (nf - 1).bit_length())


def launch(op: str, plan: KernelPlan, m: int, x, a, b, grid, n_out: int, nf: int):
    """op F: (x, w, cT) -> y; G: (x, w, g) -> GT; P: (x, g, cT) -> p (torch tensors)."""
    import torch

    mod = _module(plan, m, nf)
    batch, n_in = x.shape
    meta = {"IN": n_in, "OUT": n_out, "NF": nf, "NP": _np(nf), "BB": BB, "BO": BO}
    cdiv = lambda n, d: (n + d - 1) // d  # noqa: E731
    if op == "F":
        out = torch.empty(batch, n_out, device=x.device, dtype=torch.float32)
        mod.kf_F[(cdiv(batch, BB), cdiv(n_out, BO))](x, a, b, grid, out, batch, **meta)
    elif op == "G":
        out = torch.empty(n_out, n_in, nf, device=x.device, dtype=torch.float32)
        mod.kf_G[(n_in, cdiv(n_out, BO))](x, a, b, grid, out, batch, **meta)
    else:
        out = torch.empty(batch, n_in, device=x.device, dtype=torch.float32)
        mod.kf_P[(cdiv(batch, BB), n_in)](x, a, b, grid, out, batch, **meta)
    return out
